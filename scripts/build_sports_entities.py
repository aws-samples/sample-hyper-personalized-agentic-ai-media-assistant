#!/usr/bin/env python3
"""Build the followed-entity registry from the checked-in sports roster.

    infra/deployment/seed/sports_roster.json   teams, players, drivers (fictional demo roster)
    infra/deployment/seed/sports_aliases.json  nicknames the roster does not contain
        -> infra/lambdas/profile_settings/sports_entities.json

Aliases come from the data where it has them (a team's official name, a
driver's three-letter code) and from the alias file otherwise. Surname and
initial-surname spellings are generated by the resolver at load time, so they
are not written here. Shirt and car numbers are kept as `number` for display;
they are not aliases, because the same number belongs to several people.

Usage:
    .venv/bin/python scripts/build_sports_entities.py           # write the registry
    .venv/bin/python scripts/build_sports_entities.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROSTER = ROOT / "infra/deployment/seed/sports_roster.json"
ALIASES = ROOT / "infra/deployment/seed/sports_aliases.json"
REGISTRY = ROOT / "infra/lambdas/profile_settings/sports_entities.json"

DESCRIPTION = (
    "Sports entity registry for the followed-entity resolver. Canonical ids are what L3 stores and what "
    "consumers match on. GENERATED by scripts/build_sports_entities.py from "
    "infra/deployment/seed/sports_roster.json and sports_aliases.json; edit those, not this file. "
    "Surname and initial-surname aliases for players and drivers are generated by the resolver, "
    "so only extra spellings appear in `aliases`."
)


def _add(aliases: list[str], spelling: str | None, name: str) -> None:
    s = (spelling or "").strip()
    if s and s.casefold() != name.casefold() and s.casefold() not in (a.casefold() for a in aliases):
        aliases.append(s)


def build(roster: dict, extra: dict) -> dict:
    sport_of = {t["id"]: t["sport"] for t in roster["teams"]}
    entities = []

    def entity(row: dict, kind: str, sport: str, generated: list[str | None]) -> dict:
        aliases: list[str] = []
        for s in [*generated, *extra.get(row["id"], [])]:
            _add(aliases, s, row["name"])
        e = {"id": row["id"], "type": kind, "sport": sport, "name": row["name"]}
        if row.get("team"):
            e["team"] = row["team"]
        if row.get("number") is not None:
            e["number"] = row["number"]
        if row.get("code"):
            e["code"] = row["code"]
        e["aliases"] = aliases
        return e

    for t in roster["teams"]:
        entities.append(entity(t, "team", t["sport"], [t.get("official_name")]))
    for p in roster["players"]:
        entities.append(entity(p, "player", sport_of[p["team"]], []))
    for d in roster["drivers"]:
        entities.append(entity(d, "driver", sport_of[d["team"]], [(d.get("code") or "").lower()]))

    ids = [e["id"] for e in entities]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    unknown_teams = sorted({e["team"] for e in entities if e.get("team") and e["team"] not in sport_of})
    unknown_alias_ids = sorted(set(extra) - set(ids))
    for label, bad in (("duplicate ids", dupes), ("unknown teams", unknown_teams),
                       ("aliases for unknown ids", unknown_alias_ids)):
        if bad:
            raise SystemExit(f"{label}: {bad}")
    return {"description": DESCRIPTION, "version": 1, "entities": entities}


def render(doc: dict) -> str:
    """One entity per line, so a roster change is a one-line diff."""
    rows = [json.dumps(e, ensure_ascii=False) for e in doc["entities"]]
    body = ",\n".join(f"    {r}" for r in rows)
    return ("{\n"
            f'  "description": {json.dumps(doc["description"], ensure_ascii=False)},\n'
            f'  "version": {doc["version"]},\n'
            f'  "entities": [\n{body}\n  ]\n'
            "}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the registry does not match the roster")
    args = ap.parse_args()

    roster = json.loads(ROSTER.read_text(encoding="utf-8"))
    extra = json.loads(ALIASES.read_text(encoding="utf-8"))["aliases"]
    text = render(build(roster, extra))
    if args.check:
        current = REGISTRY.read_text(encoding="utf-8") if REGISTRY.exists() else ""
        if current != text:
            sys.exit(f"{REGISTRY.relative_to(ROOT)} is stale: run scripts/build_sports_entities.py")
        print("registry is up to date")
        return
    REGISTRY.write_text(text, encoding="utf-8")
    counts = {k: sum(1 for e in json.loads(text)["entities"] if e["type"] == k) for k in ("team", "player", "driver")}
    print(f"wrote {REGISTRY.relative_to(ROOT)}: {counts}")


if __name__ == "__main__":
    main()
